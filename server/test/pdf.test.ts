test("a one-page PDF: the text line by line, each line with its page and a box inside the page", async () => {
	const bytes = fixture("INV-2026-1041")
	const a = await parsePdf(bytes), b = await parsePdf(bytes)
	assert.deepEqual(a, b, "parsing is deterministic")
	assert.deepEqual([a.source.format, a.source.mime, a.source.size, a.source.fileHash], ["pdf", "application/pdf", bytes.length, fileHash(bytes)])
	assert.deepEqual(a.source.pages, [{ n: 1, w: PAGE.w, h: PAGE.h, rotate: 0 }])
	const lines = a.text.split("\n")
	assert.equal(lines.length, a.source.lines.length, "one source-map entry per line of text")
	for (const want of ["Invoice number: INV-2026-1041", "Freight Hamburg -> Belgrade, 3 pallets 3 410.00 1,230.00", "Net 1,415.00", "TOTAL EUR 1,415.00", "IBAN: DE89 3704 0044 0532 0130 00", "Hafenstraße 12, 20457 Hamburg, Germany"]) assert.ok(lines.includes(want), `the line "${want}"`)
	assert.deepEqual(a.source.lines.map((l) => l.line), lines.map((_, i) => i + 1), "lines are numbered from 1 on their page")
	for (const [i, l] of a.source.lines.entries()) {
		assert.equal(l.page, 1)
		assert.ok(l.box, `line ${i + 1} has a known position`)
		const [x0, y0, x1, y1] = l.box!
		assert.ok(x0 >= 0 && y0 >= 0 && x1 <= PAGE.w && y1 <= PAGE.h && x1 > x0 && y1 > y0, `the box of line ${i + 1} is inside the page`)
	}
	const total = a.source.lines[lines.indexOf("TOTAL EUR 1,415.00")]!.box!, net = a.source.lines[lines.indexOf("Net 1,415.00")]!.box!
	assert.ok(total[1] > net[3] - 1, "the total is below the net line, as on the page")
	assert.ok(total[0] > PAGE.w / 2, "and in the right-hand column")
})

test("a two-page PDF: page boundaries are kept, and two different amounts stay on their own pages", async () => {
	const p = await parsePdf(fixture("INV-2026-1049"))
	assert.equal(p.source.pages.length, 2)
	const lines = p.text.split("\n")
	const at = (s: string) => p.source.lines[lines.findIndex((l) => l.includes(s))]!
	assert.equal(at("please pay EUR 1,980.00").page, 1)
	assert.equal(at("TOTAL EUR 1,890.00").page, 2)
	assert.equal(at("NORDLICHT LOGISTIK GmbH").line, 1, "line numbers start again on each page")
	const pages = p.source.lines.map((l) => l.page)
	assert.deepEqual(pages, [...pages].sort((a, b) => a - b), "the text is in page order")
	assert.ok(lines.filter((l) => /1,980\.00|1,890\.00/.test(l)).length >= 3, "neither amount was dropped or merged")
})

