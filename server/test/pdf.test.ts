test("files that are not acceptable PDFs are refused with the reason, before or instead of parsing", async () => {
	assert.equal(sniff(Buffer.from("%PDF-1.4\n")), "pdf")
	assert.equal(sniff(Buffer.from("Invoice number: 1\n")), "text")
	assert.equal(sniff(Buffer.from([0x4d, 0x5a, 0x90, 0x00, 0x03])), "binary")
	await rejects(parsePdf(Buffer.alloc(0)), "empty", 400)
	await rejects(parsePdf(Buffer.from([0x4d, 0x5a, 0x90, 0x00, 0x03, 0x00, 0x00, 0x00])), "unsupported", 415) // an executable renamed to .pdf
	await rejects(parsePdf(Buffer.from("\x89PNG\r\n\x1a\n" + "0".repeat(200), "latin1")), "unsupported", 415)
	await rejects(parsePdf(Buffer.from("Invoice number: INV-1\nTOTAL EUR 10.00\n")), "unsupported", 415)
	await rejects(parsePdf(Buffer.from("%PDF-1.4\nthis is not a PDF at all, only the first line says so\n")), "invalid", 422)
	const good = fixture("INV-2026-1041")
	await rejects(parsePdf(good.subarray(0, 700)), "invalid", 422) // truncated
	await rejects(parsePdf(Buffer.concat([good, Buffer.alloc(LIMITS.pdfBytes)])), "too_large", 413)
	const page = (i: number) => [{ t: "text" as const, x: 56, y: 80, s: `Page ${i + 1} of a long synthetic document` }]
	await rejects(parsePdf(makePdf(Array.from({ length: LIMITS.pages + 1 }, (_, i) => page(i)))), "too_many_pages", 422)
	assert.equal((await parsePdf(makePdf(Array.from({ length: LIMITS.pages }, (_, i) => page(i))))).source.pages.length, LIMITS.pages, "the limit itself is accepted")
	const dense = Array.from({ length: 5 }, () => Array.from({ length: 60 }, (_, i) => ({ t: "text" as const, x: 40, y: 40 + i * 12, s: "A long line of synthetic text that repeats in order to exceed the limit on extracted characters. ".repeat(1), size: 8 })))
	await rejects(parsePdf(makePdf(dense)), "too_long", 413)
	await rejects(parsePdf(makePdf([[{ t: "rect", x: 60, y: 60, w: 400, h: 600, gray: 0.8 }]])), "no_text", 422) // a page with a picture of an invoice and no text layer
	await rejects(parsePdf(invoicePdf(spec("INV-2026-1041"), { encrypt: true })), "encrypted", 422)
})

