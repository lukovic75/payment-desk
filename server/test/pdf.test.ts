test("HTTP: bad uploads are refused with a reason and start nothing", async () => {
	const before = (await get("/api/state")).body.cases.length
	const cases: [string, Buffer, number, RegExp][] = [
		["setup.pdf", Buffer.from([0x4d, 0x5a, 0x90, 0x00, 0x03, 0x00, 0x00, 0x00, 0x04]), 415, /not a PDF/],
		["empty.pdf", Buffer.alloc(0), 400, /empty|Send a document/],
		["broken.pdf", fixture("INV-2026-1041").subarray(0, 600), 422, /could not be parsed as a valid PDF/],
		["scan.pdf", makePdf([[{ t: "rect", x: 60, y: 60, w: 400, h: 600, gray: 0.8 }]]), 422, /does not contain extractable text\. Scanned documents are not supported/],
		["locked.pdf", invoicePdf(spec("INV-2026-1041"), { encrypt: true }), 422, /encrypted or password-protected/],
		["long.pdf", makePdf(Array.from({ length: LIMITS.pages + 1 }, (_, i) => [{ t: "text" as const, x: 56, y: 80, s: `Synthetic page ${i + 1}` }])), 422, /supported limit is 10/],
		["huge.pdf", Buffer.concat([fixture("INV-2026-1041"), Buffer.alloc(LIMITS.pdfBytes)]), 413, /too large|larger than the supported limit|supported limit/],
	]
	for (const [name, bytes, status, re] of cases) {
		const r = await upload(name, bytes)
		assert.equal(r.status, status, name)
		assert.match(r.body.error, re, name)
		assert.doesNotMatch(r.body.error, /at .*\.(ts|js|mjs):\d+|node:internal/, "no stack trace reaches the user")
	}
	assert.equal((await post("/api/documents/inspect", { name: "x.txt", text: "%PDF-1.4 sent as text by mistake, with enough characters" })).status, 415)
	assert.equal((await post("/api/documents/inspect", { name: "x.bin", text: "binary\u0000content\u0000that is not text at all" })).status, 415)
	assert.equal((await post("/api/documents/inspect", { name: "x" })).status, 400)
	assert.equal((await post("/api/documents", { token: "no-such-token" })).status, 404)
	assert.equal((await raw("/api/pending/no-such-token/file")).status, 404)
	assert.equal((await post("/api/documents/inspect", { name: "../../../etc/passwd.pdf", pdf: fixture("INV-2026-1062").toString("base64") })).body.fileName, ".._.._.._etc_passwd.pdf", "a file name is a label, never a path")
	assert.equal((await get("/api/state")).body.cases.length, before)
	assert.equal((await get("/api/health")).body.ok, true, "the server is still answering")
})

