/**
 * PDF intake: validation, parsing, the source map, document identity, duplicates, evidence by page, and the same
 * financial controls on a PDF as on text. The parser is the desk's own (a worker thread around pdfjs); the PDFs are
 * the synthetic fixtures in server/data/documents/pdf or are written here with the small test writer.
 * No model and no network. The workflow tests run the real Mozaik runtime with the scripted model.
 */
