test("every reference into a PDF carries the page and line the source map gives it, and conflicting values keep their own pages", async () => {
	const [c] = await run([{ id: "INV-2026-1049", pdf: fixture("INV-2026-1049") }])
	const src = desk.getDocumentSource(c!.id)!
	assert.equal(src.format, "pdf")
	const text = desk.getDocumentText(c!.id)!.split("\n")
	const located = Object.values(c!.ledger).filter((e) => e.doc?.located && e.doc.docId === c!.id)
	assert.ok(located.length >= 8)
	for (const e of located) {
		const at: { page: number; line: number } = (src as any).lines[e.doc!.lineStart! - 1]
		assert.deepEqual([e.doc!.page, e.doc!.pageLine], [at.page, at.line], `${e.id} is on the page the source map says`)
		assert.ok(text[e.doc!.lineStart! - 1]!.replace(/\s+/g, " ").includes(e.doc!.excerpt.trim().replace(/\s+/g, " ").slice(0, 20)), `${e.id}: the excerpt is on that line of the parsed PDF`)
	}
	assert.equal(c!.ledger["X:gross"]!.doc!.page, 2)
	assert.deepEqual([c!.ledger["A:conflict:1:1"]!.doc!.page, c!.ledger["A:conflict:1:2"]!.doc!.page], [1, 2], "1,980.00 on page 1 and 1,890.00 on page 2")
	const ch = c!.challenges!.find((k) => k.category === "document_contradiction")!
	assert.deepEqual([ch.challenged.ref, ch.observed.ref, ch.status], ["A:conflict:1:1", "A:conflict:1:2", "requires_human_verification"], "a position in the PDF resolves nothing")
	assert.equal(outcomeOf(c!), "NEEDS_APPROVAL")
	assert.equal(c!.integrity?.ok, true)
	assert.deepEqual(c!.pdf, { pages: 2, size: fixture("INV-2026-1049").length, fileHash: fileHash(fixture("INV-2026-1049")) })
	// the original file is served back exactly as it came in
	assert.ok(desk.getDocumentFile(c!.id)!.bytes.equals(fixture("INV-2026-1049")))
	assert.equal(desk.getDocumentFile("INV-0000"), null)
})

test("re-verification: a reference with a page the PDF does not have, a wrong page, or a line outside the source map is refused", async () => {
	const bytes = fixture("INV-2026-1041")
	const [c] = await run([{ id: "INV-2026-1041", pdf: bytes }])
	assert.equal(outcomeOf(c!), "AUTO_APPROVED")
	const parsed = await parsePdf(bytes)
	const doc: SourceDocument = { id: c!.id, fileName: "INV-2026-1041.pdf", text: parsed.text, hash: contentHash(parsed.text), receivedAt: c!.receivedAt, source: { ...parsed.source, fileName: "INV-2026-1041.pdf" } }
	const s = desk.snapshot()
	const ctx = (d: SourceDocument, k: PaymentCase) => ({ policy: s.policy, vendors: s.vendors, history: s.history, purchaseOrders: loadPurchaseOrders(), verified: [], confirmed: [], cases: [k], documents: new Map([[k.id, d]]), dailyAutoApproved: 0 })
	assert.equal(checkIntegrity(c!, ctx(doc, c!)).ok, true, "untouched, it verifies")
	const broken = (mutate: (k: PaymentCase, d: SourceDocument) => void, why: RegExp) => {
		const k = structuredClone(c!), d = structuredClone(doc)
		mutate(k, d)
		const r = checkIntegrity(k, ctx(d, k))
		assert.equal(r.ok, false)
		assert.ok(r.findings.some((f) => f.kind === "broken_reference" && f.critical && why.test(f.detail)), `expected ${why}, got ${r.findings.map((f) => f.detail).join(" | ")}`)
	}
	broken((k) => { k.ledger["X:gross"]!.doc!.page = 2 }, /says page 2, but that line of the document is on page 1/)
	broken((_, d) => { d.source!.lines[c!.ledger["X:gross"]!.doc!.lineStart! - 1]!.page = 7 }, /page 7, which the PDF does not have/)
	broken((_, d) => { d.source!.lines.length = 3 }, /not in the source map/)
	broken((k) => { k.ledger["X:gross"]!.doc!.lineStart = 2; k.ledger["X:gross"]!.doc!.lineEnd = 2 }, /not at line 2/) // an excerpt that is real, cited at another line
	broken((k) => { k.ledger["X:iban"]!.doc!.docId = "INV-2026-1049" }, /not this case's document/) // evidence from another document
})

