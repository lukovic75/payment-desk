	assert.equal(preview.source.pages.length, 2)
	assert.ok(preview.text.includes("please pay EUR 2,150.00"))

	// processing is a separate, explicit request
	const started = await post("/api/documents", { token: seen.body.token })
	assert.equal(started.status, 200)
	assert.deepEqual([started.body.id, started.body.fileName, started.body.pdf.pages], ["INV-2026-1064", "INV-2026-1064.pdf", 2])
	assert.equal((await post("/api/documents", { token: seen.body.token })).status, 404, "a document is processed once")
