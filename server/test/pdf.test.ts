const rejects = (p: Promise<unknown>, code: string, status?: number) => assert.rejects(p, (e: any) => e instanceof DocumentError && e.code === code && (status == null || e.status === status), `expected a "${code}" refusal`)
const control = (c: PaymentCase, id: string) => c.controls.find((k) => k.id === id)

/** Adds PDFs (and text documents) to an empty desk and runs them. Each PDF goes through the parser first, as an upload does. */
async function run(items: ({ id: string; pdf: Buffer; name?: string } | { id: string; text: string })[], script: Record<string, unknown> = {}) {
	desk.resetDesk()
	desk.setModelRunner(scriptedModel({ readings: ALL, policy: "AUTO_APPROVED", audits: { ...SHOWCASE_RESPONSES.audits, ...PDF_RESPONSES.audits }, ...script }))
	const out: PaymentCase[] = []
	for (const it of items) {
		if ("pdf" in it) { const p = await parsePdf(it.pdf); out.push(desk.addDocument(it.id, p.text, "user", undefined, { fileName: it.name ?? `${it.id}.pdf`, bytes: it.pdf, source: p.source })) }
		else out.push(desk.addDocument(it.id, it.text, "user"))
		await desk.whenSettled(30_000)
	}
	return out.map((c) => desk.peek(c.id))
}

