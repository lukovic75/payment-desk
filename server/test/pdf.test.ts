test("the same PDF under another name, the same text in another file, and the same obligation in another document are three different findings", async () => {
	const bytes = fixture("INV-2026-1062")
	// 1. the same bytes, renamed
	const [first, renamed] = await run([{ id: "INV-2026-1062", pdf: bytes }, { id: "scan-0099", pdf: bytes, name: "scan_0099.pdf" }])
	assert.equal(outcomeOf(first!), "AUTO_APPROVED")
	assert.equal(outcomeOf(renamed!), "BLOCKED")
	assert.match(control(renamed!, "duplicate")!.detail, /byte for byte the same file as INV-2026-1062\.pdf/)
	assert.equal(renamed!.runs.length, 0, "stopped at intake: no agent was run")
	assert.equal(renamed!.draft, null)
	// 2. another file (different metadata, so different bytes) with the same text
	const resaved = invoicePdf(spec("INV-2026-1062"), { title: "Re-exported copy", producer: "Another PDF tool" })
	assert.notEqual(fileHash(resaved), fileHash(bytes))
	const [, copy] = await run([{ id: "INV-2026-1062", pdf: bytes }, { id: "INV-2026-1062-copy", pdf: resaved }])
	assert.equal(outcomeOf(copy!), "BLOCKED")
	assert.match(control(copy!, "duplicate")!.detail, /text of this document is exactly the text of INV-2026-1062\.pdf.*although the files differ/)
	assert.equal(copy!.runs.length, 0)
	// 3. a different document for the same vendor and invoice number: the financial duplicate control, after the agents have read it
	const [, obligation] = await run([{ id: "INV-2026-1041", text: TEXT["INV-2026-1041"]!.text }, { id: "INV-2026-1041-pdf", pdf: fixture("INV-2026-1041") }], { readings: { ...ALL, "INV-2026-1041-pdf": READINGS["INV-2026-1041"]! } })
	assert.equal(outcomeOf(obligation!), "BLOCKED")
	assert.match(control(obligation!, "duplicate")!.detail, /Same vendor and invoice number as INV-2026-1041/)
	assert.ok(obligation!.runs.length > 0, "this one had to be read to be recognised")
	assert.equal(desk.snapshot().cases.filter((k) => k.draft).length, 1, "one obligation, one draft")
	// 4. an invoice already in the payment history
	const [paid] = await run([{ id: "INV-7701-rappel", pdf: fixture("INV-7701-rappel") }])
	assert.equal(outcomeOf(paid!), "BLOCKED")
	assert.ok(control(paid!, "duplicate")!.refs.includes("H:H-0001"))
	assert.equal(desk.findSame(contentHash("nothing like it"), null), null)
})

